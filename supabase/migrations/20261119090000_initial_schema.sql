-- Abarilela Peace Cup: the whole schema as it stood when the app moved from SQLite to Postgres.
-- Run it in the Supabase SQL Editor (paste the whole file, then Run). Run the files in this
-- folder in name order. Safe to run again: everything is "IF NOT EXISTS".
-- Never edit a migration that has been run; add a new file with a later timestamp instead.

CREATE EXTENSION IF NOT EXISTS citext;

CREATE TABLE IF NOT EXISTS seasons (
  id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name           text    NOT NULL,
  format         text    NOT NULL DEFAULT 'league' CHECK (format IN ('league', 'groups')),
  points_win     integer NOT NULL DEFAULT 3,
  points_draw    integer NOT NULL DEFAULT 1,
  points_loss    integer NOT NULL DEFAULT 0,
  highlight_top  integer NOT NULL DEFAULT 4,
  relegation     integer NOT NULL DEFAULT 0,
  -- the admin can pin one season to the home page (otherwise it's chosen automatically)
  pinned         integer NOT NULL DEFAULT 0 CHECK (pinned IN (0, 1)),
  created_at     text    NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_seasons_single_pin ON seasons(pinned) WHERE pinned = 1;

CREATE TABLE IF NOT EXISTS league_groups (
  id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  season_id  integer NOT NULL REFERENCES seasons(id) ON DELETE CASCADE,
  name       citext  NOT NULL,
  UNIQUE (season_id, name)
);

CREATE TABLE IF NOT EXISTS teams (
  id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  season_id  integer NOT NULL REFERENCES seasons(id) ON DELETE CASCADE,
  name       citext  NOT NULL,
  group_id   integer REFERENCES league_groups(id) ON DELETE SET NULL,
  UNIQUE (season_id, name)
);

CREATE TABLE IF NOT EXISTS playing_dates (
  season_id  integer NOT NULL REFERENCES seasons(id) ON DELETE CASCADE,
  date       text    NOT NULL,  -- YYYY-MM-DD
  PRIMARY KEY (season_id, date)
);

CREATE TABLE IF NOT EXISTS matches (
  id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  season_id     integer NOT NULL REFERENCES seasons(id) ON DELETE CASCADE,
  round         integer NOT NULL,
  date          text,             -- YYYY-MM-DD
  kickoff       text,             -- HH:MM
  venue         text,
  -- NULL stage = league/group match that counts toward the table; otherwise e.g. 'Final'.
  stage         text,
  group_id      integer REFERENCES league_groups(id) ON DELETE SET NULL,
  home_team_id  integer NOT NULL REFERENCES teams(id) ON DELETE CASCADE,
  away_team_id  integer NOT NULL REFERENCES teams(id) ON DELETE CASCADE,
  home_score    integer,
  away_score    integer
);
CREATE INDEX IF NOT EXISTS idx_matches_season ON matches(season_id, round);
CREATE INDEX IF NOT EXISTS idx_matches_date ON matches(season_id, date, kickoff);

CREATE TABLE IF NOT EXISTS players (
  id        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  team_id   integer NOT NULL REFERENCES teams(id) ON DELETE CASCADE,
  name      text    NOT NULL,
  number    integer,
  position  text CHECK (position IN ('GK', 'DF', 'MF', 'FW'))
);
CREATE INDEX IF NOT EXISTS idx_players_team ON players(team_id);

CREATE TABLE IF NOT EXISTS match_events (
  id                integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  match_id          integer NOT NULL REFERENCES matches(id) ON DELETE CASCADE,
  type              text    NOT NULL CHECK (type IN ('goal', 'own_goal', 'yellow', 'red')),
  -- goal/own_goal: the team credited with the goal; cards: the player's team
  team_id           integer NOT NULL REFERENCES teams(id) ON DELETE CASCADE,
  player_id         integer NOT NULL REFERENCES players(id) ON DELETE CASCADE,
  assist_player_id  integer REFERENCES players(id) ON DELETE SET NULL,
  minute            integer,
  -- added (stoppage) time, e.g. a goal in 90+3 is minute 90, added_minute 3
  added_minute      integer
);
CREATE INDEX IF NOT EXISTS idx_events_match ON match_events(match_id);
CREATE INDEX IF NOT EXISTS idx_events_player ON match_events(player_id);

CREATE TABLE IF NOT EXISTS users (
  id                 integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username           citext  NOT NULL UNIQUE,
  name               text    NOT NULL,
  password_hash      text    NOT NULL,
  role               text    NOT NULL DEFAULT 'fan' CHECK (role IN ('fan', 'official', 'admin')),
  favourite_team_id  integer REFERENCES teams(id) ON DELETE SET NULL,
  created_at         text    NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')
);
-- there is exactly one admin
CREATE UNIQUE INDEX IF NOT EXISTS idx_users_single_admin ON users(role) WHERE role = 'admin';

-- Only a hash of each session token is stored, so a leaked database can't be used to sign in.
CREATE TABLE IF NOT EXISTS sessions (
  token_hash  text    PRIMARY KEY,
  user_id     integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  expires_at  bigint  NOT NULL   -- unix seconds
);
CREATE INDEX IF NOT EXISTS idx_sessions_user ON sessions(user_id);
